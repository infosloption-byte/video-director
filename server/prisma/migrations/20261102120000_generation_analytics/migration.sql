CREATE TABLE `generation_traces` (
  `id` VARCHAR(64) NOT NULL,
  `project_id` VARCHAR(64) NULL,
  `user_id` VARCHAR(64) NULL,
  `stage` VARCHAR(50) NOT NULL,
  `operation` VARCHAR(80) NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `provider` VARCHAR(50) NULL,
  `model` VARCHAR(100) NULL,
  `started_at` DATETIME(3) NOT NULL,
  `finished_at` DATETIME(3) NOT NULL,
  `duration_ms` INTEGER NOT NULL,
  `input_tokens` INTEGER NULL,
  `output_tokens` INTEGER NULL,
  `cost_usd` DECIMAL(14,8) NULL,
  `cost_source` VARCHAR(50) NULL,
  `metadata` JSON NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `generation_traces_created_at_idx`(`created_at`),
  INDEX `generation_traces_user_id_created_at_idx`(`user_id`, `created_at`),
  INDEX `generation_traces_project_id_created_at_idx`(`project_id`, `created_at`),
  INDEX `generation_traces_stage_status_created_at_idx`(`stage`, `status`, `created_at`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
